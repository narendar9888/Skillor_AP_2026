BEGIN;

CREATE TYPE skill_type_enum AS ENUM ('learn', 'teach');
CREATE TYPE match_status_enum AS ENUM ('active', 'inactive', 'rejected');
CREATE TYPE request_status_enum AS ENUM ('pending', 'accepted', 'declined');

CREATE TABLE users (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    email               VARCHAR(320) NOT NULL UNIQUE,
    password_hash       VARCHAR(255) NOT NULL,
    bio                 TEXT,
    location            VARCHAR(255),
    profile_pic_url     VARCHAR(2048),
    rating              DOUBLE PRECISION,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_rating_range CHECK (rating IS NULL OR (rating >= 1 AND rating <= 5))
);

CREATE TABLE skills (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name          VARCHAR(255) NOT NULL UNIQUE,
    description         TEXT,
    category_id         INTEGER,
    icon_url            VARCHAR(2048)
);

CREATE TABLE user_skills (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    skill_id            INTEGER NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,
    skill_type          skill_type_enum NOT NULL,
    proficiency         TEXT,
    experience_years    INTEGER,
    CONSTRAINT user_skills_experience_nonnegative CHECK (experience_years IS NULL OR experience_years >= 0),
    CONSTRAINT user_skills_no_duplicates UNIQUE (user_id, skill_id, skill_type)
);

CREATE TABLE matches (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user1_id            INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    user2_id            INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    matched_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status              match_status_enum NOT NULL DEFAULT 'active',
    CONSTRAINT matches_distinct_users CHECK (user1_id <> user2_id)
);

CREATE UNIQUE INDEX matches_unique_user_pair
    ON matches (LEAST(user1_id, user2_id), GREATEST(user1_id, user2_id));

CREATE TABLE exchange_requests (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id            INTEGER REFERENCES matches(id) ON DELETE SET NULL,
    sender_id           INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    skill_to_learn_id   INTEGER NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,
    skill_to_teach_id   INTEGER NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,
    status              request_status_enum NOT NULL DEFAULT 'pending',
    request_message     TEXT,
    requested_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notifications (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type                TEXT NOT NULL,
    reference_id        INTEGER,
    message             VARCHAR(1000) NOT NULL,
    is_read             BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE conversations (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id            INTEGER NOT NULL REFERENCES matches(id) ON DELETE RESTRICT,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE messages (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id     INTEGER NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_id           INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    content             TEXT NOT NULL,
    sent_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_read             BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT messages_content_not_blank CHECK (length(btrim(content)) > 0)
);

CREATE TABLE reviews (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id            INTEGER NOT NULL REFERENCES matches(id) ON DELETE RESTRICT,
    reviewer_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reviewee_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    rating              INTEGER NOT NULL,
    comment             TEXT,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reviews_rating_range CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT reviews_distinct_users CHECK (reviewer_id <> reviewee_id),
    CONSTRAINT reviews_one_per_reviewer_per_match UNIQUE (match_id, reviewer_id)
);


CREATE INDEX idx_user_skills_skill_id ON user_skills(skill_id);
CREATE INDEX idx_matches_user1_id ON matches(user1_id);
CREATE INDEX idx_matches_user2_id ON matches(user2_id);
CREATE INDEX idx_exchange_requests_match_id ON exchange_requests(match_id);
CREATE INDEX idx_exchange_requests_sender_status ON exchange_requests(sender_id, status);
CREATE INDEX idx_exchange_requests_skill_to_learn ON exchange_requests(skill_to_learn_id);
CREATE INDEX idx_exchange_requests_skill_to_teach ON exchange_requests(skill_to_teach_id);
CREATE INDEX idx_notifications_user_read_created ON notifications(user_id, is_read, created_at DESC);
CREATE INDEX idx_conversations_match_id ON conversations(match_id);
CREATE INDEX idx_messages_conversation_sent ON messages(conversation_id, sent_at DESC);
CREATE INDEX idx_messages_sender_id ON messages(sender_id);
CREATE INDEX idx_reviews_reviewee_id ON reviews(reviewee_id);

COMMIT;
